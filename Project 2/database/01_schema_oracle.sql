-- Drop existing tables in reverse dependency order
BEGIN
   FOR cur_rec IN (SELECT table_name FROM user_tables WHERE table_name IN (
       'BOOKING_AUDIT_LOG', 'PAYMENTS', 'RATES', 'BOOKING_SEATS', 'BOOKINGS',
       'SHOWS', 'SHOWTIMES', 'SCREENS', 'MOVIE_ACTOR_BASED', 'ANIMATED_MOVIE',
       'DOCUMENTARY', 'MOVIES', 'MEMBERSHIPS', 'USER_PROFILES', 'USERS'
   )) LOOP
      EXECUTE IMMEDIATE 'DROP TABLE ' || cur_rec.table_name || ' CASCADE CONSTRAINTS';
   END LOOP;
END;
/

-- ----------------------------------------------------------------------------
-- 1. USERS: Base user account entity
-- ----------------------------------------------------------------------------
CREATE TABLE users (
    user_id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    email VARCHAR2(150) NOT NULL UNIQUE,
    password_hash VARCHAR2(255) DEFAULT 'pbkdf2_sha256$default' NOT NULL,
    role VARCHAR2(20) DEFAULT 'CUSTOMER' CHECK (role IN ('CUSTOMER', 'STAFF', 'ADMIN')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- ----------------------------------------------------------------------------
-- 2. USER_PROFILES: 1-to-1 extension with demographic & contact information
-- ----------------------------------------------------------------------------
CREATE TABLE user_profiles (
    user_id NUMBER PRIMARY KEY REFERENCES users(user_id) ON DELETE CASCADE,
    phone VARCHAR2(20),
    date_of_birth DATE,
    address VARCHAR2(255),
    bio VARCHAR2(500)
);

-- ----------------------------------------------------------------------------
-- 3. MEMBERSHIPS: Membership tier discount (Gold/Silver/Platinum)
-- ----------------------------------------------------------------------------
CREATE TABLE memberships (
    user_id NUMBER PRIMARY KEY REFERENCES users(user_id) ON DELETE CASCADE,
    membership_type VARCHAR2(30) DEFAULT 'GOLD' CHECK (membership_type IN ('SILVER', 'GOLD', 'PLATINUM')),
    discount_percent NUMBER(5,2) DEFAULT 10.00 CHECK (discount_percent >= 0 AND discount_percent <= 100),
    started_on DATE DEFAULT SYSDATE NOT NULL,
    expires_on DATE DEFAULT ADD_MONTHS(SYSDATE, 12) NOT NULL,
    status VARCHAR2(20) DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'EXPIRED', 'SUSPENDED'))
);

-- ----------------------------------------------------------------------------
-- 4. MOVIES: Supertype entity for movie catalog
-- ----------------------------------------------------------------------------
CREATE TABLE movies (
    movie_id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    title VARCHAR2(200) NOT NULL,
    language VARCHAR2(50) NOT NULL,
    duration NUMBER NOT NULL CHECK (duration > 0),
    release_year NUMBER(4) NOT NULL CHECK (release_year >= 1900),
    movie_type VARCHAR2(50) DEFAULT 'ACTION',
    poster VARCHAR2(500),
    rating VARCHAR2(10) DEFAULT '8.5',
    votes VARCHAR2(20) DEFAULT '12.5k'
);

-- ----------------------------------------------------------------------------
-- 5. EER SUBTYPES: Subtype tables for movie specialization
-- ----------------------------------------------------------------------------
CREATE TABLE movie_actor_based (
    movie_id NUMBER PRIMARY KEY REFERENCES movies(movie_id) ON DELETE CASCADE,
    lead_actor VARCHAR2(100) NOT NULL
);

CREATE TABLE animated_movie (
    movie_id NUMBER PRIMARY KEY REFERENCES movies(movie_id) ON DELETE CASCADE,
    animation_style VARCHAR2(100) NOT NULL,
    studio VARCHAR2(100) NOT NULL
);

CREATE TABLE documentary (
    movie_id NUMBER PRIMARY KEY REFERENCES movies(movie_id) ON DELETE CASCADE,
    subject VARCHAR2(200) NOT NULL,
    narrator VARCHAR2(100) NOT NULL
);

-- ----------------------------------------------------------------------------
-- 6. SCREENS: Cinema auditorium details
-- ----------------------------------------------------------------------------
CREATE TABLE screens (
    screen_id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    screen_name VARCHAR2(100) NOT NULL UNIQUE,
    screen_type VARCHAR2(50) NOT NULL,
    capacity NUMBER DEFAULT 40 NOT NULL CHECK (capacity > 0)
);

-- ----------------------------------------------------------------------------
-- 7. SHOWS: Scheduled movie screenings in screens
-- ----------------------------------------------------------------------------
CREATE TABLE shows (
    show_id VARCHAR2(50) PRIMARY KEY,
    movie_id NUMBER NOT NULL REFERENCES movies(movie_id) ON DELETE CASCADE,
    screen_id NUMBER NOT NULL REFERENCES screens(screen_id) ON DELETE CASCADE,
    screen_name VARCHAR2(100) NOT NULL,
    show_date DATE NOT NULL,
    show_time VARCHAR2(20) NOT NULL,
    price NUMBER(10,2) NOT NULL CHECK (price >= 0)
);

-- ----------------------------------------------------------------------------
-- 8. BOOKINGS: Transactional booking records
-- ----------------------------------------------------------------------------
CREATE TABLE bookings (
    booking_id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    user_id NUMBER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    movie_id NUMBER NOT NULL REFERENCES movies(movie_id),
    show_id VARCHAR2(50) NOT NULL REFERENCES shows(show_id),
    show_date DATE NOT NULL,
    show_time VARCHAR2(20) NOT NULL,
    screen_name VARCHAR2(100) NOT NULL,
    total NUMBER(10,2) NOT NULL CHECK (total >= 0),
    status VARCHAR2(20) DEFAULT 'CONFIRMED' CHECK (status IN ('CONFIRMED', 'CANCELLED', 'REFUNDED')),
    payment_status VARCHAR2(30) DEFAULT 'USER_REPORTED',
    payment_reference VARCHAR2(100),
    refund_requested_at TIMESTAMP,
    refund_request_amount NUMBER(10,2),
    switched_from_show_id VARCHAR2(50),
    switched_at TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- ----------------------------------------------------------------------------
-- 9. BOOKING_SEATS: Normalized individual seat tickets
-- ----------------------------------------------------------------------------
CREATE TABLE booking_seats (
    ticket_no NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    booking_id NUMBER NOT NULL REFERENCES bookings(booking_id) ON DELETE CASCADE,
    show_id VARCHAR2(50) NOT NULL REFERENCES shows(show_id),
    seat_no VARCHAR2(10) NOT NULL CHECK (REGEXP_LIKE(seat_no, '^[A-E][1-8]$')),
    ticket_type VARCHAR2(20) DEFAULT 'adult' CHECK (ticket_type IN ('adult', 'child', 'senior')),
    price NUMBER(10,2) DEFAULT 0,
    status VARCHAR2(20) DEFAULT 'CONFIRMED' CHECK (status IN ('CONFIRMED', 'CANCELLED', 'REFUNDED'))
);

-- ----------------------------------------------------------------------------
-- 10. PAYMENTS: Financial ledger and UPI tracking
-- ----------------------------------------------------------------------------
CREATE TABLE payments (
    payment_id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    booking_id NUMBER NOT NULL REFERENCES bookings(booking_id) ON DELETE CASCADE,
    amount NUMBER(10,2) NOT NULL CHECK (amount >= 0),
    payment_method VARCHAR2(50) DEFAULT 'UPI',
    payment_status VARCHAR2(30) DEFAULT 'COMPLETED',
    payment_reference VARCHAR2(100),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- ----------------------------------------------------------------------------
-- 11. RATES: Verified customer reviews and ratings
-- ----------------------------------------------------------------------------
CREATE TABLE rates (
    rate_id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    user_id NUMBER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    movie_id NUMBER NOT NULL REFERENCES movies(movie_id) ON DELETE CASCADE,
    rating NUMBER(2,1) NOT NULL CHECK (rating >= 1 AND rating <= 10),
    review_text VARCHAR2(1000),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_user_movie_rating UNIQUE (user_id, movie_id)
);

-- ----------------------------------------------------------------------------
-- 12. BOOKING_AUDIT_LOG: Enterprise audit table tracking status transitions
-- ----------------------------------------------------------------------------
CREATE TABLE booking_audit_log (
    log_id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    booking_id NUMBER NOT NULL,
    old_status VARCHAR2(20),
    new_status VARCHAR2(20),
    action_type VARCHAR2(50) NOT NULL,
    changed_by VARCHAR2(100) DEFAULT 'SYSTEM',
    change_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    notes VARCHAR2(500)
);

-- ----------------------------------------------------------------------------
-- Performance Indexes for OLTP optimization
-- ----------------------------------------------------------------------------
CREATE INDEX idx_shows_movie_date ON shows(movie_id, show_date);
CREATE INDEX idx_bookings_user ON bookings(user_id, status);
CREATE INDEX idx_seats_show_seat ON booking_seats(show_id, seat_no, status);
CREATE INDEX idx_rates_movie ON rates(movie_id);
