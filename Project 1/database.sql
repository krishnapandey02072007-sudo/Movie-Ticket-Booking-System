CREATE DATABASE IF NOT EXISTS cinema_booking CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

USE cinema_booking;

CREATE TABLE IF NOT EXISTS users (user_id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);

CREATE TABLE IF NOT EXISTS movies (movie_id INT PRIMARY KEY, title VARCHAR(200) NOT NULL, language VARCHAR(40) NOT NULL, duration INT NOT NULL, release_year INT NOT NULL, movie_type VARCHAR(80) NOT NULL, poster TEXT NOT NULL, rating VARCHAR(20) NOT NULL, votes VARCHAR(30) NOT NULL);

CREATE TABLE IF NOT EXISTS showtimes (show_id VARCHAR(80) PRIMARY KEY, movie_id INT NOT NULL, show_date DATE NOT NULL, show_time TIME NOT NULL, screen_name VARCHAR(80) NOT NULL, price DECIMAL(10,2) NOT NULL, FOREIGN KEY (movie_id) REFERENCES movies(movie_id));

CREATE TABLE IF NOT EXISTS bookings (booking_id BIGINT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, movie_id INT NOT NULL, show_date DATE NOT NULL, show_id VARCHAR(80) NOT NULL, show_time VARCHAR(30) NOT NULL, screen_name VARCHAR(80) NOT NULL, total DECIMAL(10,2) NOT NULL, status ENUM('CONFIRMED','CANCELLED') DEFAULT 'CONFIRMED', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY (user_id) REFERENCES users(user_id), FOREIGN KEY (movie_id) REFERENCES movies(movie_id));

CREATE TABLE IF NOT EXISTS booking_seats (booking_id BIGINT NOT NULL, seat_no VARCHAR(8) NOT NULL, ticket_type ENUM('adult','child','senior') DEFAULT 'adult', PRIMARY KEY (booking_id, seat_no), FOREIGN KEY (booking_id) REFERENCES bookings(booking_id) ON DELETE CASCADE);

